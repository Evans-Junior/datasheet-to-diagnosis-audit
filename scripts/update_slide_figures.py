"""Re-embed the generated figures into the presented deck.

The deck embeds two pictures, fig_size.png and fig_corpora.png. Until
2026-11-19 both were hand-pasted: no script produced them and nothing tied them
to results/tables, so a rescore could leave them stale with nothing complaining.
Both are now generated by scripts/build_paper_figures.py and re-embedded here,
which makes the deck and the paper show the SAME charts. The paper figures are
drawn at the width the paper prints them at; the deck panels are wider, so the
deck scales them UP, which costs nothing. Drawing for the deck instead and
letting LaTeX scale down is what produced 4pt text (D120, D121).

A reviewer found three faults in the old fig_size, all of them one fault: the
legend keyed colour only while the chart also used marker shape, so Qwen3's
noise floor read as OLMo's and the other families' floors read as Pythia
points. The replacement separates the controlled series from the confounded
one. D114, D116.

Run from the project root, after the deck has been assembled.
"""
import sys, os
from pptx import Presentation
from pptx.util import Inches, Emu, Pt

DECK = "Ethics In AI Final Presentation.pptx"
OUT = sys.argv[1] if len(sys.argv) > 1 else DECK
NEW = {"fig_size.png":    "results/figures/paper/fig_size.png",
       "fig_corpora.png": "results/figures/paper/fig_corpora.png"}

prs = Presentation(DECK)
swapped = 0
for idx, slide in enumerate(prs.slides, start=1):
    for sh in list(slide.shapes):
        if sh.shape_type != 13:
            continue
        cnv = sh._element._nvXxPr.cNvPr
        alt = cnv.get("descr")
        src = NEW.get(alt or "")
        if not src:
            continue
        assert os.path.exists(src), f"{src} missing: run build_paper_figures.py first"

        # the panel this picture lives in, so the resize can be checked
        L, T, W, H = (Emu(v).inches for v in (sh.left, sh.top, sh.width, sh.height))
        panel = None
        for other in slide.shapes:
            if other is sh or other.has_text_frame and other.text_frame.text.strip():
                continue
            try:
                oL, oT = Emu(other.left).inches, Emu(other.top).inches
                oW, oH = Emu(other.width).inches, Emu(other.height).inches
            except (TypeError, ValueError):
                continue
            if oL <= L and oT <= T and oL + oW >= L + W and oT + oH >= T + H:
                if panel is None or oW * oH < panel[2] * panel[3]:
                    panel = (oL, oT, oW, oH)
        assert panel, f"slide {idx}: no panel found around {alt}"

        image_part, rId = slide.part.get_or_add_image_part(src)
        sh._element.blipFill.blip.rEmbed = rId
        px, py = image_part.image.size
        aspect = px / py

        # keep the picture's left edge and centre it in the vertical room it had
        pL, pT, pW, pH = panel
        avail_w = min(W + 0.14, pL + pW - 0.14 - L)
        new_w = avail_w
        new_h = new_w / aspect
        if new_h > H:
            new_h = H
            new_w = new_h * aspect
        new_y = T + (H - new_h) / 2.0

        # The clearance below was asserted and not constructed, so a figure
        # whose aspect happened to fill the panel exactly failed the build by
        # a ten-thousandth of an inch. Shrink to fit instead; the assert stays
        # as the check that the shrink worked. Centring moves the top down by
        # half of whatever height is removed, so the bottom rises by half.
        over = (new_y + new_h) - (pT + pH - 0.06)
        if over > 0:
            new_h -= 2 * over
            new_w = new_h * aspect
            new_y = T + (H - new_h) / 2.0

        sh.left, sh.top = Inches(L), Inches(new_y)
        sh.width, sh.height = Inches(new_w), Inches(new_h)
        assert L + new_w <= pL + pW - 0.05, (L + new_w, pL + pW)
        assert new_y + new_h <= pT + pH - 0.05, (new_y + new_h, pT + pH)
        print(f"  slide {idx}: {alt} -> {src}  "
              f"{new_w:.2f} x {new_h:.2f} in at y {new_y:.2f}")
        swapped += 1

assert swapped == len(NEW), (swapped, len(NEW))

# the caption beside it must quote the same statistics the new panel A does
for slide in prs.slides:
    for sh in slide.shapes:
        if not sh.has_text_frame:
            continue
        p0 = sh.text_frame.paragraphs[0]
        if not p0.runs:
            continue
        t = p0.runs[0].text
        if t.startswith("Gap vs size ρ 0.948"):
            p0.runs[0].text = (
                "Across all ten, gap vs size ρ 0.948 while the floor sits at "
                "ρ 0.353, not significant. Within Pythia, the only series where "
                "size is the sole variable, the gap still rises, ρ 0.857 [6].")
            for r in p0.runs[1:]:
                r.text = ""
            print("  caption rewritten to match the figure")

prs.save(OUT)
print("saved", OUT)
