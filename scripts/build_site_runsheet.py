"""Build the defence site's run-of-show fragment from the pitch deck itself.

WHY THIS IS A SCRIPT. The site (an Artifact, not in this repo) is the one
presentation artefact with no build step, which is how it came to be reporting
the October instrument in November (D102). A run of show is worse than a stale
number, because it is a list of timings somebody will stand up and follow. So
the fragment is generated from the deck, and regenerating it after a deck edit
is the whole update procedure.

It reads the `[Ns]` markers in the speaker notes, which is the same source the
deck's own budget check uses, so the site and the deck cannot disagree about
how long the talk is.

    qa_venv/bin/python scripts/build_site_runsheet.py
    -> docs/site_runsheet.html   (paste into the site's #present section)

The site is at https://claude.ai/artifact/8KWd3KmpB58kcQirgVvuN4 and is updated
by publishing to that url, never by creating a new one.
"""
from __future__ import annotations

import html
import re
import sys
from pathlib import Path

from pptx import Presentation

ROOT = Path(__file__).resolve().parents[1]
DECK = ROOT / "Datasheet_to_Diagnosis_5min_Pitch_ Reviewed.pptx.pptx"
OUT = ROOT / "docs" / "site_runsheet.html"
SLOT = 300                      # a five minute slot, in seconds

e = html.escape


def mmss(n: int) -> str:
    return f"{n // 60}:{n % 60:02d}"


def read_deck(path: Path) -> list[dict]:
    """One row per slide: its title, its budget, and the line its notes open on."""
    prs = Presentation(str(path))
    rows, cum = [], 0
    for i, s in enumerate(prs.slides, 1):
        title = ""
        for sh in s.shapes:
            if sh.has_text_frame and sh.text_frame.text.strip():
                t = sh.text_frame.text.strip().split("\n")[0].strip()
                # The slide-number box is a text shape too, and on a Canva
                # export it often comes first in z-order.
                if len(t) > 3 and not t.isdigit():
                    title = t
                    break
        notes = ""
        if s.has_notes_slide and s.notes_slide.notes_text_frame is not None:
            notes = (s.notes_slide.notes_text_frame.text or "").strip()
        m = re.search(r"\[(\d+)s\]", notes)
        secs = int(m.group(1)) if m else None
        if secs:
            cum += secs
        rows.append({
            "n": i, "title": title, "secs": secs, "cum": cum,
            "build": bool(re.match(r"\[build", notes)),
            "first": re.sub(r"^\[[^\]]*\]\s*", "", notes.split("\n")[0]).strip(),
        })
    return rows


def render(rows: list[dict]) -> tuple[str, int]:
    total = max(r["cum"] for r in rows)
    out = []
    for r in rows:
        cls = ' class="build"' if r["build"] else ""
        takes = (f'{r["secs"]}s' if r["secs"]
                 else ('<span class="sm">click</span>' if r["build"] else "&mdash;"))
        at = mmss(r["cum"]) if r["secs"] else ""
        if r["build"]:
            line = ('<span class="sm">second half of the slide before '
                    "&mdash; nothing new on screen</span>")
        else:
            line = e(r["first"][:132]) + ("&hellip;" if len(r["first"]) > 132 else "")
        out.append(
            f'<tr{cls} data-cum="{r["cum"]}" data-n="{r["n"]}">'
            f'<td class="num">{r["n"]}</td><td class="num">{at}</td>'
            f'<td class="num">{takes}</td>'
            f'<td><strong>{e(r["title"])}</strong><div class="sm">{line}</div></td></tr>')
    return "\n".join(out), total


def main() -> int:
    if not DECK.exists():
        print(f"no deck at {DECK}")
        return 1
    rows = read_deck(DECK)
    body, total = render(rows)
    spoken = sorted((r for r in rows if r["secs"]), key=lambda r: -r["secs"])[:6]
    cost = "".join(f'<li><strong>slide {r["n"]}</strong> at {r["secs"]}s '
                   f'&mdash; {e(r["title"])}</li>' for r in spoken)
    OUT.write_text(
        f"<!-- generated by scripts/build_site_runsheet.py from {DECK.name} -->\n"
        f"<!-- {len(rows)} slides, {total}s target, {total - SLOT}s over a {SLOT}s slot -->\n"
        f'<ul class="tight">{cost}</ul>\n'
        f'<table id="runsheet"><tbody>\n{body}\n</tbody></table>\n',
        encoding="utf-8")
    print(f"{len(rows)} slides, budget {mmss(total)}, "
          f"{mmss(total - SLOT)} over a {mmss(SLOT)} slot")
    print(f"  -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
